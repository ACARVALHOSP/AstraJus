async page => {
  await page.setViewportSize({width:390,height:900});
  await page.goto('http://127.0.0.1:5185/novo/#/contatos');
  await page.locator('.tabela-detalhes-botao').first().waitFor();
  if(await page.locator('.tabela-detalhes-botao').first().getAttribute('aria-expanded')!=='true') await page.locator('.tabela-detalhes-botao').first().click();
  const detalhe=page.locator('.tabela-detalhes-linha:not([hidden])').first();
  if(!(await detalhe.textContent()).includes('sobrenome'.repeat(14)+'@exemplo.com.br')) throw new Error('E-mail completo indisponivel');
  const id=await page.locator('.tabela-detalhes-botao').first().getAttribute('aria-controls');
  if(await page.locator('[id="'+id+'"]').count()!==1) throw new Error('ID de detalhes invalido');
  await page.getByRole('checkbox',{name:'Selecionar todas as linhas'}).focus();
  await page.keyboard.press('Space');
  if(await page.locator('tbody input[type=checkbox]:checked').count()!==2) throw new Error('Selecao de contatos');
  await page.setViewportSize({width:1440,height:900});
  await page.evaluate(() => new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
  if(await page.locator('tbody input[type=checkbox]:checked').count()!==2) throw new Error('Selecao perdida no resize');
  await page.screenshot({path:'.scratch/tabelas-responsivas/contatos-desktop.png'});
  await page.goto('http://127.0.0.1:5185/novo/#/financeiro');
  await page.setViewportSize({width:390,height:900});
  await page.locator('.tabela-detalhes-botao').first().waitFor();
  if(await page.locator('.tabela-detalhes-botao').first().getAttribute('aria-expanded')!=='true') await page.locator('.tabela-detalhes-botao').first().click();
  await page.route('**/lancamentos/l1', route=>route.fulfill({json:{ok:true}}));
  await page.getByRole('checkbox',{name:'Recebido',exact:true}).first().focus();
  await page.keyboard.press('Space');
  if(!await page.getByRole('checkbox',{name:'Recebido',exact:true}).first().isChecked()) throw new Error('Checkbox pago sem handler');
  await page.locator('.tabela-ordenacao summary').click();
  await page.locator('.tabela-ordenacao').getByRole('button',{name:'Cliente',exact:true}).click();
  if(!(await page.locator('.tabela-ordenacao').textContent()).includes('Cliente · crescente')) throw new Error('Ordenacao complementar');
  await page.screenshot({path:'.scratch/tabelas-responsivas/financeiro-mobile.png',fullPage:true});
  await page.goto('http://127.0.0.1:5185/novo/#/publicacoes-oab');
  await page.getByRole('button',{name:'Expandir publicação pub1'}).click();
  if(!await page.locator('#oab-detalhes-pub1').isVisible()) throw new Error('Expansao OAB');
  await page.locator('.tabela-detalhes-botao').click();
  if(!await page.locator('.tabela-detalhes-linha:not([hidden])').isVisible()) throw new Error('Complementos OAB');
  await page.getByRole('checkbox',{name:'Selecionar publicação pub1',exact:true}).focus();
  await page.keyboard.press('Space');
  if(!await page.getByRole('button',{name:'Marcar como tratada',exact:true}).isVisible()) throw new Error('Acao em lote OAB');
  if(await page.locator('.tabela-adaptavel').evaluate(t=>t.scrollWidth>t.clientWidth+1)) throw new Error('Overflow OAB expandida');
  await page.getByRole('button',{name:'Alternar tema'}).click();
  await page.screenshot({path:'.scratch/tabelas-responsivas/publicacoes-dark.png',fullPage:true});
}
